void PS2_ShortPoll(void) 
{
  CS_L; 
  PS2_Delayus(10); 
  PS2_Cmd(0x01); 
  PS2_Cmd(0x42); 
  PS2_Cmd(0X00); 
  PS2_Cmd(0x00); 
  PS2_Cmd(0x00); 
  CS_H; 
  PS2_Delayus(10);
}


