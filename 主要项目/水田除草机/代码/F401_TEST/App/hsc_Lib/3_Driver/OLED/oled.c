static void OLED_IIC_Start()
{

	OLED_SCLK_Set();
	OLED_SDIN_Set();
	OLED_SDIN_Clr();
	OLED_SCLK_Clr();
}
/**********************************************
//IIC Stop
**********************************************/
static void OLED_IIC_Stop()
{
	OLED_SCLK_Set();
	//	OLED_SCLK_Clr();
	OLED_SDIN_Clr();
	OLED_SDIN_Set();
}

static void OLED_IIC_Wait_Ack()
{

	// ????????ack???
	OLED_SCLK_Set();
	OLED_SCLK_Clr();
}
/**********************************************
// IIC Write byte
**********************************************/
static void OLED_Write_IIC_Byte(unsigned char IIC_Byte)
{
	unsigned char i;
	unsigned char m, da;
	da = IIC_Byte;
	OLED_SCLK_Clr();
	for (i = 0; i < 8; i++)
	{
		m = da;
		//	OLED_SCLK_Clr();
		m = m & 0x80;
		if (m == 0x80)
		{
			OLED_SDIN_Set();
		}
		else
			OLED_SDIN_Clr();
		da = da << 1;
		OLED_SCLK_Set();
		OLED_SCLK_Clr();
	}
}
/**********************************************
// IIC Write Command
**********************************************/
static void OLED_Write_IIC_Command(unsigned char IIC_Command)
{
	OLED_IIC_Start();
	OLED_Write_IIC_Byte(IIC_SLAVE_ADDR); // Slave address,SA0=0
	OLED_IIC_Wait_Ack();
	OLED_Write_IIC_Byte(0x00); // write command
	OLED_IIC_Wait_Ack();
	OLED_Write_IIC_Byte(IIC_Command);
	OLED_IIC_Wait_Ack();
	OLED_IIC_Stop();
}
/**********************************************
// IIC Write Data
**********************************************/
static void OLED_Write_IIC_Data(unsigned char IIC_Data)
{
	OLED_IIC_Start();
	OLED_Write_IIC_Byte(IIC_SLAVE_ADDR); // D/C#=0; R/W#=0
	OLED_IIC_Wait_Ack();
	OLED_Write_IIC_Byte(0x40); // write data
	OLED_IIC_Wait_Ack();
	OLED_Write_IIC_Byte(IIC_Data);
	OLED_IIC_Wait_Ack();
	OLED_IIC_Stop();
}
void OLED_WR_Byte(unsigned dat, unsigned cmd)
{
	if (cmd)
	{

		OLED_Write_IIC_Data(dat);
	}
	else
	{
		OLED_Write_IIC_Command(dat);
	}
}

