/**
  * @brief  ??OLED????????
  * @param  x1: ???x???? (0-127)
  * @param  y1: ???y???? (0-63)
  * @param  x2: ???x???? (0-127)
  * @param  y2: ???y???? (0-63)
  * @param  color: ??? (0-???, 1-???)
  * @retval ??
  */
void OLED_DrawLine(u8 x1, u8 y1, u8 x2, u8 y2, u8 color)
{
	int dx, dy, sx, sy, err, e2;
	
	// ???????????????????
	if (x1 > 127) x1 = 127;
	if (x2 > 127) x2 = 127;
	if (y1 > 63) y1 = 63;
	if (y2 > 63) y2 = 63;
	
	// Bresenham?????
	dx = (x2 > x1) ? (x2 - x1) : (x1 - x2);
	dy = (y2 > y1) ? (y2 - y1) : (y1 - y2);
	sx = (x1 < x2) ? 1 : -1;
	sy = (y1 < y2) ? 1 : -1;
	err = dx - dy;
	
	while (1)
	{
		OLED_DrawPoint(x1, y1, color);
		
		if (x1 == x2 && y1 == y2)
			break;
		
		e2 = 2 * err;
		if (e2 > -dy)
		{
			err -= dy;
			x1 += sx;
		}
		if (e2 < dx)
		{
			err += dx;
			y1 += sy;
		}
	}
}

