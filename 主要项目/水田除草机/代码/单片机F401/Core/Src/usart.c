//串口 接收处理函数
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
 if(huart->Instance==USART1)
 {
     // UART1接摄像头：逐字节喂入Cam_uart协议解析
     Cam_Uart_Parse_Byte(USART1_RX_Byte);
     // 调试命令：只在绑定串口上解析，且协议要求'$'开头ASCII行
     if (DEBUG_UART_IS_BOUND(huart)) {
         Debug_Uart_Parse_Byte(USART1_RX_Byte);
     }
     UART_Start_Receive_IT(huart, &USART1_RX_Byte, 1); // 收到一个数据后进入中断
     //HAL_UART_Receive_IT(huart, &USART1_RX_Byte, 1);
 }
 if(huart->Instance==USART2)
 {
     // 当USART2被调试串口占用时，不再把数据喂给WIT解析器，避免串口数据互相干扰
     #if (DEBUG_UART_BIND_USART != 2)
     WitSerialDataIn(USART2_RX_Byte);
     #endif
     if (DEBUG_UART_IS_BOUND(huart)) {
         Debug_Uart_Parse_Byte(USART2_RX_Byte);
     }
     UART_Start_Receive_IT(huart, &USART2_RX_Byte, 1); // 收到一个数据后进入中断
     //HAL_UART_Transmit(&huart1, &USART2_RX_Byte, 1, 0xffff);
     //HAL_GPIO_WritePin(GPIOC, GPIO_PIN_7, GPIO_PIN_TOGGLE);
 }
}

